#!/usr/bin/env node
/**
 * Generates `src/generated/i18n-keys.ts` from the English locale.
 *
 * With `t()` typed against this union, a mistyped or removed message key is a
 * compile error instead of a string that silently renders as itself. The file is
 * committed so `tsc` works on a fresh clone; CI regenerates it and fails if the
 * result differs, which keeps it honest.
 *
 *   node scripts/gen-i18n-types.mjs           write
 *   node scripts/gen-i18n-types.mjs --check   verify it is up to date
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const SOURCE = "src/static/_locales/en/messages.json";
const OUTPUT = "src/generated/i18n-keys.ts";

const messages = JSON.parse(readFileSync(SOURCE, "utf8"));
const keys = Object.keys(messages).sort();

const contents = `// Generated by scripts/gen-i18n-types.mjs from ${SOURCE}. Do not edit.

/** Every message key defined in the locales. */
export type MessageKey =
${keys.map((key) => `  | "${key}"`).join("\n")};

/** Runtime list, for the checker and for exhaustiveness assertions. */
export const MESSAGE_KEYS: readonly MessageKey[] = [
${keys.map((key) => `  "${key}",`).join("\n")}
] as const;
`;

if (process.argv.includes("--check")) {
  const current = (() => {
    try {
      return readFileSync(OUTPUT, "utf8");
    } catch {
      return "";
    }
  })();
  if (current !== contents) {
    console.error(`  ✗ ${OUTPUT} is stale — run: npm run gen:i18n`);
    process.exit(1);
  }
  console.log(`  ✓ ${keys.length} message keys, generated types up to date`);
} else {
  mkdirSync("src/generated", { recursive: true });
  writeFileSync(OUTPUT, contents);
  console.log(`generated ${OUTPUT} with ${keys.length} keys`);
}
